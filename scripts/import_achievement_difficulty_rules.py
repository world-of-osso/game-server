#!/usr/bin/env python3
"""Compile pinned criteria whose only condition is a TC DungeonDifficulty68 tree."""
import argparse
import collections
import hashlib
from pathlib import Path

from import_achievement_single_modifiers import read_rows

DUNGEON_DIFFICULTY = 68
CONDITIONS = ('StartEvent', 'StartTimer', 'FailEvent', 'EligibilityWorldStateID')


def leaf_difficulty(row, children):
    """(operator, Difficulty.db2 ID) of a plain DungeonDifficulty leaf, else None."""
    if int(row['Type']) != DUNGEON_DIFFICULTY or children:
        return None
    if int(row['SecondaryAsset']) or int(row['TertiaryAsset']):
        return None
    return int(row['Operator']), int(row['Asset'])


def tree_rule(root, modifiers, children):
    """TC ModifierTreeSatisfied over difficulty leaves: (allowed?, IDs).

    All4 of SingleTrue2 leaves needs one shared ID; All4 of SingleFalse3 leaves
    excludes every ID; Some8 needing max(Amount,1)==1 of SingleTrue2 leaves allows any.
    """
    parent = modifiers[root]
    if (int(parent['Type']), int(parent['Asset'])) != (0, 0):
        return None
    if int(parent['SecondaryAsset']) or int(parent['TertiaryAsset']):
        return None
    leaves = [leaf_difficulty(modifiers[child], children[child]) for child in children[root]]
    if not leaves or None in leaves:
        return None
    operators = {operator for operator, _ in leaves}
    ids = tuple(sorted({difficulty for _, difficulty in leaves}))
    operator, amount = int(parent['Operator']), int(parent['Amount'])
    if operator == 4 and operators == {2} and len(ids) == 1:
        return True, ids
    if operator == 4 and operators == {3}:
        return False, ids
    if operator == 8 and operators == {2} and max(amount, 1) == 1:
        return True, ids
    return None


def qualified_difficulty_rules(criteria, modifiers):
    """Criteria ID -> (modifier root, allowed?, Difficulty IDs)."""
    children = collections.defaultdict(list)
    for row_id, row in modifiers.items():
        children[int(row['Parent'])].append(row_id)
    qualified = {}
    for row_id, row in criteria.items():
        root = int(row['ModifierTreeId'])
        if not root or root not in modifiers or any(int(row[key]) for key in CONDITIONS):
            continue
        rule = tree_rule(root, modifiers, children)
        if rule:
            qualified[row_id] = (root, *rule)
    return qualified


def generate_source(criteria_path, modifiers_path, output):
    qualified = qualified_difficulty_rules(read_rows(criteria_path), read_rows(modifiers_path))
    lines = [
        '// Generated by scripts/import_achievement_difficulty_rules.py; do not edit.',
        '// TC CriteriaHandler.cpp1723-1751 operators over DungeonDifficulty68 (2090-2093) leaves.',
        f'// Criteria SHA256 {hashlib.sha256(criteria_path.read_bytes()).hexdigest()}.',
        f'// ModifierTree SHA256 {hashlib.sha256(modifiers_path.read_bytes()).hexdigest()}.',
        'use super::DifficultyRule;',
        '',
        'pub(super) fn difficulty_rule(criteria: u32, modifier: u32) -> Option<DifficultyRule> {',
        '    match (criteria, modifier) {',
    ]
    for criterion, (modifier, allowed, ids) in sorted(qualified.items()):
        listed = ', '.join(str(difficulty) for difficulty in ids)
        lines.append(f'        ({criterion}, {modifier}) => Some(DifficultyRule {{ allowed: {str(allowed).lower()}, ids: &[{listed}] }}),')
    lines += ['        _ => None,', '    }', '}', '']
    output.write_text('\n'.join(lines))
    print(f'Compiled {len(qualified)} DungeonDifficulty predicates.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--criteria', type=Path, required=True)
    parser.add_argument('--modifiers', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate_source(args.criteria, args.modifiers, args.output)


if __name__ == '__main__':
    main()
