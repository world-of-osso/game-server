#!/usr/bin/env python3
"""Compile pinned criteria whose only condition is a TC difficulty tree."""
import argparse
import collections
import hashlib
from pathlib import Path

from import_achievement_single_modifiers import read_rows

LEGACY_DUNGEON_DIFFICULTY = 20
DUNGEON_DIFFICULTY = 68
CONDITIONS = ('StartEvent', 'StartTimer', 'FailEvent', 'EligibilityWorldStateID')


def legacy_difficulties(difficulty_path):
    """Difficulty.db2 OldEnumValue -> Difficulty IDs (TC CriteriaHandler.cpp1860-1865)."""
    legacy = collections.defaultdict(set)
    for row_id, row in read_rows(difficulty_path).items():
        if int(row['OldEnumValue']) >= 0:
            legacy[int(row['OldEnumValue'])].add(row_id)
    return dict(legacy)


def leaf_difficulties(row, children, legacy):
    """(operator, admitted Difficulty IDs) of a plain difficulty leaf, else None.

    DungeonDifficulty68 admits its Asset; LegacyDungeonDifficulty20 admits every
    Difficulty whose OldEnumValue equals its Asset.
    """
    if children or int(row['SecondaryAsset']) or int(row['TertiaryAsset']):
        return None
    kind, asset = int(row['Type']), int(row['Asset'])
    if kind == DUNGEON_DIFFICULTY:
        return int(row['Operator']), frozenset({asset})
    if kind == LEGACY_DUNGEON_DIFFICULTY:
        return int(row['Operator']), frozenset(legacy.get(asset, ()))
    return None


def tree_rule(root, modifiers, children, legacy):
    """TC ModifierTreeSatisfied over difficulty leaves: (allowed?, IDs).

    All4 of SingleTrue2 leaves admits their shared IDs; All4 of SingleFalse3 leaves
    excludes every listed ID; Some8 needing max(Amount,1)==1 of SingleTrue2 leaves
    admits any listed ID.
    """
    parent = modifiers[root]
    if (int(parent['Type']), int(parent['Asset'])) != (0, 0):
        return None
    if int(parent['SecondaryAsset']) or int(parent['TertiaryAsset']):
        return None
    leaves = [leaf_difficulties(modifiers[child], children[child], legacy) for child in children[root]]
    if not leaves or None in leaves:
        return None
    operators = {operator for operator, _ in leaves}
    sets = [ids for _, ids in leaves]
    operator, amount = int(parent['Operator']), int(parent['Amount'])
    if operator == 4 and operators == {2}:
        shared = frozenset.intersection(*sets)
        return (True, tuple(sorted(shared))) if shared else None
    if operator == 4 and operators == {3}:
        return False, tuple(sorted(frozenset.union(*sets)))
    if operator == 8 and operators == {2} and max(amount, 1) == 1:
        admitted = frozenset.union(*sets)
        return (True, tuple(sorted(admitted))) if admitted else None
    return None


def qualified_difficulty_rules(criteria, modifiers, legacy):
    """Criteria ID -> (modifier root, allowed?, Difficulty IDs)."""
    children = collections.defaultdict(list)
    for row_id, row in modifiers.items():
        children[int(row['Parent'])].append(row_id)
    qualified = {}
    for row_id, row in criteria.items():
        root = int(row['ModifierTreeId'])
        if not root or root not in modifiers or any(int(row[key]) for key in CONDITIONS):
            continue
        rule = tree_rule(root, modifiers, children, legacy)
        if rule:
            qualified[row_id] = (root, *rule)
    return qualified


def generate_source(criteria_path, modifiers_path, difficulty_path, output):
    legacy = legacy_difficulties(difficulty_path)
    qualified = qualified_difficulty_rules(read_rows(criteria_path), read_rows(modifiers_path), legacy)
    lines = [
        '// Generated by scripts/import_achievement_difficulty_rules.py; do not edit.',
        '// TC CriteriaHandler.cpp1723-1751 operators over LegacyDungeonDifficulty20 (1860-1865)',
        '// and DungeonDifficulty68 (2090-2093) leaves.',
        f'// Criteria SHA256 {hashlib.sha256(criteria_path.read_bytes()).hexdigest()}.',
        f'// ModifierTree SHA256 {hashlib.sha256(modifiers_path.read_bytes()).hexdigest()}.',
        f'// Difficulty SHA256 {hashlib.sha256(difficulty_path.read_bytes()).hexdigest()}.',
        'use super::DifficultyRule;',
        '',
        'pub(super) fn difficulty_rule(criteria: u32, modifier: u32) -> Option<DifficultyRule> {',
        '    match (criteria, modifier) {',
    ]
    for criterion, (modifier, allowed, ids) in sorted(qualified.items()):
        listed = ', '.join(str(difficulty) for difficulty in ids)
        lines.append(f'        ({criterion}, {modifier}) => Some(DifficultyRule {{ allowed: {str(allowed).lower()}, ids: &[{listed}] }}),')
    lines += ['        _ => None,', '    }', '}', '']
    output.write_text('\n'.join(lines))
    print(f'Compiled {len(qualified)} difficulty predicates.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--criteria', type=Path, required=True)
    parser.add_argument('--modifiers', type=Path, required=True)
    parser.add_argument('--difficulty', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate_source(args.criteria, args.modifiers, args.difficulty, args.output)


if __name__ == '__main__':
    main()
