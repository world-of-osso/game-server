#!/usr/bin/env python3
"""Compile pinned criteria whose only condition is one sourced TC modifier."""
import argparse
import collections
import csv
import hashlib
from pathlib import Path

# CriteriaType -> (ModifierTreeType, valid asset). TC CriteriaHandler.cpp
# 1890-1892 PlayerClass26; 2212-2215 BattlePetSpecies91 equals miscValue1.
FAMILIES = {
    221: (26, lambda class_id: 1 <= class_id <= 13),
    155: (91, lambda species: species > 0),
    160: (91, lambda species: species > 0),
    162: (91, lambda species: species > 0),
}


def read_rows(path):
    with path.open() as source:
        return {int(row['ID']): row for row in csv.DictReader(source)}


def qualified_single_modifiers(criteria, modifiers):
    """Criteria ID -> (modifier root, modifier asset) for only AND4 -> SingleTrue2."""
    children = collections.defaultdict(list)
    for row_id, row in modifiers.items():
        children[int(row['Parent'])].append(row_id)
    qualified = {}
    for row_id, row in criteria.items():
        kind, criterion_asset = int(row['Type']), int(row['Asset'])
        family = FAMILIES.get(kind)
        if family is None:
            continue
        if kind in (160, 162):
            if not 1 <= criterion_asset <= 25:
                continue
        elif criterion_asset != 0:
            continue
        if any(int(row[key]) for key in ('StartEvent', 'StartTimer', 'FailEvent', 'EligibilityWorldStateID')):
            continue
        root = int(row['ModifierTreeId'])
        branch = children[root]
        if root not in modifiers or len(branch) != 1:
            continue
        parent, leaf = modifiers[root], modifiers[branch[0]]
        if (int(parent['Operator']), int(parent['Type']), int(parent['Asset'])) != (4, 0, 0):
            continue
        modifier_type, valid_asset = family
        if (int(leaf['Operator']), int(leaf['Type'])) != (2, modifier_type) or children[branch[0]]:
            continue
        if any(int(node[key]) for node in (parent, leaf) for key in ('SecondaryAsset', 'TertiaryAsset')):
            continue
        asset = int(leaf['Asset'])
        if valid_asset(asset):
            qualified[row_id] = (root, asset)
    return qualified


def generate_source(criteria_path, modifiers_path, output):
    qualified = qualified_single_modifiers(read_rows(criteria_path), read_rows(modifiers_path))
    lines = [
        '// Generated by scripts/import_achievement_single_modifiers.py; do not edit.',
        '// TC PlayerClass26 (type221) and BattlePetSpecies91 (types155/160/162); only AND4 -> SingleTrue2.',
        f'// Criteria SHA256 {hashlib.sha256(criteria_path.read_bytes()).hexdigest()}.',
        f'// ModifierTree SHA256 {hashlib.sha256(modifiers_path.read_bytes()).hexdigest()}.',
        'pub fn single_modifier_asset(criteria: u32, modifier: u32) -> Option<u32> {',
        '    match (criteria, modifier) {',
    ]
    for criterion, (modifier, asset) in sorted(qualified.items()):
        lines.append(f'        ({criterion}, {modifier}) => Some({asset}),')
    lines += ['        _ => None,', '    }', '}', '']
    output.write_text('\n'.join(lines))
    print(f'Compiled {len(qualified)} single-modifier predicates.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--criteria', type=Path, required=True)
    parser.add_argument('--modifiers', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate_source(args.criteria, args.modifiers, args.output)


if __name__ == '__main__':
    main()
