  id1 INTEGER NOT NULL DEFAULT 0,
  id2 INTEGER NOT NULL DEFAULT 0,
  id3 INTEGER NOT NULL DEFAULT 0,
  map INTEGER NOT NULL DEFAULT 0,
  zoneId INTEGER NOT NULL DEFAULT 0,
  areaId INTEGER NOT NULL DEFAULT 0,
