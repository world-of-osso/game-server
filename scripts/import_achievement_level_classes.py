#!/usr/bin/env python3
"""Compile pinned ReachMaxLevel predicates with only TC PlayerClass modifiers."""
import argparse
import collections
import csv
import hashlib
from pathlib import Path


def read_rows(path):
    with path.open() as source:
        return {int(row['ID']): row for row in csv.DictReader(source)}


def qualified_level_classes(criteria, modifiers):
    children = collections.defaultdict(list)
    for row_id, row in modifiers.items():
        children[int(row['Parent'])].append(row_id)
    qualified = {}
    for row_id, row in criteria.items():
        if int(row['Type']) != 221 or int(row['Asset']) != 0:
            continue
        if any(int(row[key]) for key in ('StartEvent', 'StartTimer', 'FailEvent', 'EligibilityWorldStateID')):
            continue
        root = int(row['ModifierTreeId'])
        branch = children[root]
        if root not in modifiers or len(branch) != 1:
            continue
        parent, leaf = modifiers[root], modifiers[branch[0]]
        if (int(parent['Operator']), int(parent['Type']), int(parent['Asset'])) != (4, 0, 0):
            continue
        if (int(leaf['Operator']), int(leaf['Type'])) != (2, 26) or children[branch[0]]:
            continue
        if any(int(node[key]) for node in (parent, leaf) for key in ('SecondaryAsset', 'TertiaryAsset')):
            continue
        class_id = int(leaf['Asset'])
        if 1 <= class_id <= 13:
            qualified[row_id] = (root, class_id)
    return qualified


def generate_source(criteria_path, modifiers_path, output):
    qualified = qualified_level_classes(read_rows(criteria_path), read_rows(modifiers_path))
    lines = [
        '// Generated by scripts/import_achievement_level_classes.py; do not edit.',
        '// TC CriteriaHandler.cpp1890-1892 PlayerClass; only AND4 -> SingleTrue2.',
        f'// Criteria SHA256 {hashlib.sha256(criteria_path.read_bytes()).hexdigest()}.',
        f'// ModifierTree SHA256 {hashlib.sha256(modifiers_path.read_bytes()).hexdigest()}.',
        'pub(super) fn max_level_class(criteria: u32, modifier: u32) -> Option<u8> {',
        '    match (criteria, modifier) {',
    ]
    for criterion, (modifier, class_id) in sorted(qualified.items()):
        lines.append(f'        ({criterion}, {modifier}) => Some({class_id}),')
    lines += ['        _ => None,', '    }', '}', '']
    output.write_text('\n'.join(lines))
    print(f'Compiled {len(qualified)} max-level class predicates.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--criteria', type=Path, required=True)
    parser.add_argument('--modifiers', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate_source(args.criteria, args.modifiers, args.output)


if __name__ == '__main__':
    main()
