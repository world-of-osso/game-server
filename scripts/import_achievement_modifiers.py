#!/usr/bin/env python3
"""Compile pinned all-of M+ modifier trees; unknown conditions stay unsupported."""
import argparse
import csv
import hashlib
from pathlib import Path

CONDITIONS = ('StartEvent', 'StartTimer', 'FailEvent', 'EligibilityWorldStateID')


def read_rows(path):
    with path.open() as source:
        return {int(row['ID']): row for row in csv.DictReader(source)}


def collect_requirements(root, modifiers, children, visiting=frozenset()):
    if root not in modifiers or root in visiting:
        return None
    row = modifiers[root]
    operator, kind, asset = (int(row[key]) for key in ('Operator', 'Type', 'Asset'))
    if int(row['SecondaryAsset']) or int(row['TertiaryAsset']):
        return None
    branch = children.get(root, [])
    if operator == 4 and kind == 0 and branch:
        leaves = []
        for child in branch:
            found = collect_requirements(child, modifiers, children, visiting | {root})
            if found is None:
                return None
            leaves.extend(found)
        return leaves
    if operator != 2 or branch:
        return None
    if kind == 248 and asset == 0:
        return [('in_time', True)]
    fields = {247: 'min_level', 249: 'challenge_map', 39: 'player_level'}
    if kind not in fields or asset < 0:
        return None
    return [(fields[kind], asset)]


def qualified_mythic_criteria(criteria, modifiers):
    children = {}
    for row_id, row in modifiers.items():
        children.setdefault(int(row['Parent']), []).append(row_id)
    qualified = {}
    for row_id, row in criteria.items():
        if int(row['Type']) != 216 or int(row['Asset']) != 0:
            continue
        if any(int(row[key]) for key in CONDITIONS):
            continue
        root = int(row['ModifierTreeId'])
        leaves = collect_requirements(root, modifiers, children)
        if leaves is None:
            continue
        requirements = dict(modifier=root, min_level=0, challenge_map=None, player_level=None, in_time=False)
        for field, value in leaves:
            if field == 'min_level':
                requirements[field] = max(requirements[field], value)
            elif field == 'in_time':
                requirements[field] = True
            elif requirements[field] is not None and requirements[field] != value:
                break  # Contradictory all-of predicates do not describe an earnable criterion.
            else:
                requirements[field] = value
        else:
            qualified[row_id] = requirements
    return qualified


def generate_source(criteria_path, modifiers_path, output):
    qualified = qualified_mythic_criteria(read_rows(criteria_path), read_rows(modifiers_path))
    lines = [
        '// Generated by scripts/import_achievement_modifiers.py; do not edit.',
        f'// Mainline {criteria_path.parent.name}; ONLY all-of operators and verified completion inputs.',
        f'// Criteria SHA256 {hashlib.sha256(criteria_path.read_bytes()).hexdigest()}.',
        f'// ModifierTree SHA256 {hashlib.sha256(modifiers_path.read_bytes()).hexdigest()}.',
        'use super::MythicRequirements;',
        '',
        'pub(super) fn mythic_requirements(criteria: u32, modifier: u32) -> Option<MythicRequirements> {',
        '    match (criteria, modifier) {',
    ]
    for row_id, req in sorted(qualified.items()):
        optional = lambda key: 'None' if req[key] is None else f'Some({req[key]})'
        lines.append(f'        ({row_id}, {req["modifier"]}) => Some(MythicRequirements {{ min_level: {req["min_level"]}, challenge_map: {optional("challenge_map")}, player_level: {optional("player_level")}, in_time: {str(req["in_time"]).lower()} }}),')
    lines += ['        _ => None,', '    }', '}', '']
    output.write_text('\n'.join(lines))
    print(f'Compiled{len(qualified)} pinned M+ criterion predicates; other modifier trees remain unsupported.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--criteria', type=Path, required=True)
    parser.add_argument('--modifiers', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate_source(args.criteria, args.modifiers, args.output)


if __name__ == '__main__':
    main()
