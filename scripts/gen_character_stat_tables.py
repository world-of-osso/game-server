#!/usr/bin/env python3
"""Generate crates/server-catalog/src/character_stats_data.rs.

Sources:
- SimC engine/dbc/sc_extra_data.inc: __gt_class_stats_by_level (class base
  Str/Agi/Sta/Int) and __gt_race_stats (racial modifiers). Not in any DB2 or
  game table; SimC collects them in game.
- Local CASC game tables (casc-local FDIDs 1391642, 1391664, 1391669), saved as
  data/gametables/{hppersta,basemp,combatratings}.txt.
- Item-level game tables (FDIDs 1391670, 1980632, 1391643), saved as
  data/gametables/{combatratingsmultbyilvl,staminamultbyilvl,itemsocketcostperlevel}.txt.

Usage: scripts/gen_character_stat_tables.py [SIMC_DIR] [GAMETABLES_DIR]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIMC = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / "Repos/simc")
GAMETABLES = Path(sys.argv[2] if len(sys.argv) > 2 else ROOT / "data/gametables")
OUT = ROOT / "crates/server-catalog/src/character_stats_data.rs"
LEVELS = 90
CLASSES = 13

# SimC race row name -> ChrRaces ID.
RACE_IDS = {
    "Human": 1, "Orc": 2, "Dwarf": 3, "Night Elf": 4, "Undead": 5, "Tauren": 6,
    "Gnome": 7, "Troll": 8, "Goblin": 9, "Blood Elf": 10, "Draenei": 11,
    "Worgen": 22, "Pandaren": 24, "Pandaren - Alliance": 25, "Pandaren - Horde": 26,
    "Nightborne": 27, "Highmountain Tauren": 28, "Void Elf": 29,
    "Lightforged Draenei": 30, "Zandalari Troll": 31, "Kul Tiran": 32,
    "Dark Iron Dwarf": 34, "Vulpera": 35, "Mag'har Orc": 36, "Mechagnome": 37,
}
# basemp.txt column -> ChrClasses ID.
CLASS_COLUMNS = {
    "Warrior": 1, "Paladin": 2, "Hunter": 3, "Rogue": 4, "Priest": 5,
    "Death Knight": 6, "Shaman": 7, "Mage": 8, "Warlock": 9, "Monk": 10,
    "Druid": 11, "Demon Hunter": 12, "Evoker": 13,
}
RATINGS = {
    "CRIT": "Crit - Spell",
    "HASTE": "Haste - Spell",
    "MASTERY": "Mastery",
    "VERSATILITY": "Versatility - Damage Done",
    "DODGE": "Dodge",
    "PARRY": "Parry",
    "BLOCK": "Block",
    "SPEED": "Speed",
    "LEECH": "Lifesteal",
    "AVOIDANCE": "Avoidance",
}
ROW = re.compile(r"\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}")


def class_stats(text):
    body = text.split("__gt_class_stats_by_level")[1].split("__gt_race_stats")[0]
    blocks = re.split(r"\n  \{ // ", body)[1:]
    assert len(blocks) == CLASSES + 1, len(blocks)
    table = []
    for block in blocks:
        rows = [tuple(int(v) for v in m.groups()[:4]) for m in ROW.finditer(block)]
        assert len(rows) >= LEVELS, len(rows)
        table.append(rows[:LEVELS])
    return table


def race_stats(text):
    body = text.split("__gt_race_stats[] =")[1].split("};")[0]
    mods = []
    for line in body.splitlines():
        m = ROW.search(line)
        name = line.split("//")[-1].strip() if "//" in line else ""
        if m and name in RACE_IDS:
            mods.append((RACE_IDS[name], tuple(int(v) for v in m.groups()[:4])))
    assert len(mods) == len(RACE_IDS), len(mods)
    return sorted(mods)


def game_table(name, limit=LEVELS):
    lines = (GAMETABLES / name).read_text().splitlines()
    header = lines[0].split("\t")
    rows = [dict(zip(header, line.split("\t"))) for line in lines[1:]]
    for index, row in enumerate(rows, 1):
        assert int(row[header[0]]) == index, (name, index)
    return rows[:limit]


# combatratingsmultbyilvl / staminamultbyilvl columns, SimC combat_rating_multiplier_type order.
ILVL_MULT_COLUMNS = ["Armor Multiplier", "Weapon Multiplier", "Trinket Multiplier", "Jewelry Multiplier"]


def ilvl_multipliers(const, name, doc):
    rows = game_table(name, None)
    body = ", ".join("[" + fmt_floats(r[c] for c in ILVL_MULT_COLUMNS) + "]" for r in rows)
    return [
        "",
        f"/// {doc} `[item level - 1]` = (armor, weapon, trinket, jewelry).",
        "#[rustfmt::skip]",
        f"pub const {const}: [[f32; 4]; {len(rows)}] = [{body}];",
    ]


def fmt_levels(values):
    return ", ".join(values)


def fmt_floats(values):
    return ", ".join(repr(float(v)) for v in values)


def main():
    extra = (SIMC / "engine/dbc/sc_extra_data.inc").read_text()
    stats = class_stats(extra)
    races = race_stats(extra)
    hp = game_table("hppersta.txt")
    mp = game_table("basemp.txt")
    cr = game_table("combatratings.txt")
    out = [
        "// Generated by scripts/gen_character_stat_tables.py; do not edit.",
        "// Class/race base stats: SimC engine/dbc/sc_extra_data.inc",
        "// (__gt_class_stats_by_level, __gt_race_stats).",
        "// Game tables: local CASC 12.x gametables/{hppersta,basemp,combatratings,",
        "// combatratingsmultbyilvl,staminamultbyilvl,itemsocketcostperlevel}.txt.",
        "",
        "/// `[class][level - 1]` = base (Str, Agi, Sta, Int); class 0 is unused.",
        "#[rustfmt::skip]",
        f"pub const CLASS_BASE_STATS: [[[u16; 4]; {LEVELS}]; {CLASSES + 1}] = [",
    ]
    for rows in stats:
        out.append("    [" + ", ".join(f"[{s}, {a}, {t}, {i}]" for s, a, t, i in rows) + "],")
    out += [
        "];",
        "",
        "/// `(ChrRaces ID, (Str, Agi, Sta, Int))` racial modifiers, sorted by ID.",
        "#[rustfmt::skip]",
        "pub const RACE_STAT_MODS: &[(u8, [i16; 4])] = &[",
    ]
    out += [f"    ({race}, [{s}, {a}, {t}, {i}])," for race, (s, a, t, i) in races]
    out += [
        "];",
        "",
        "/// Health per stamina, `[level - 1]` (gtHpPerSta).",
        "#[rustfmt::skip]",
        f"pub const HP_PER_STAMINA: [f32; {LEVELS}] = [{fmt_floats(r['Health'] for r in hp)}];",
        "",
        "/// Base mana `[class][level - 1]` (gtBaseMP); 0 = no mana.",
        "#[rustfmt::skip]",
        f"pub const BASE_MANA: [[u32; {LEVELS}]; {CLASSES + 1}] = [",
        f"    [0; {LEVELS}],",
    ]
    by_id = {class_id: column for column, class_id in CLASS_COLUMNS.items()}
    for class_id in range(1, CLASSES + 1):
        out.append(f"    [{fmt_levels(r[by_id[class_id]] for r in mp)}],")
    out.append("];")
    for const, column in RATINGS.items():
        out += [
            "",
            f"/// Rating per 1% (mastery: per point), {column}, `[level - 1]` (gtCombatRatings).",
            "#[rustfmt::skip]",
            f"pub const {const}_RATING: [f32; {LEVELS}] = [{fmt_floats(r[column] for r in cr)}];",
        ]
    out += ilvl_multipliers(
        "COMBAT_RATING_MULT_BY_ILVL", "combatratingsmultbyilvl.txt", "Item rating multiplier (gtCombatRatingsMultByILvl)"
    )
    out += ilvl_multipliers(
        "STAMINA_MULT_BY_ILVL", "staminamultbyilvl.txt", "Item stamina multiplier (gtStaminaMultByILvl)"
    )
    socket = game_table("itemsocketcostperlevel.txt", None)
    out += [
        "",
        "/// Stat budget one socket costs, `[item level - 1]` (gtItemSocketCostPerLevel).",
        "#[rustfmt::skip]",
        f"pub const SOCKET_COST_BY_ILVL: [f32; {len(socket)}] = [{fmt_floats(r['Socket Cost'] for r in socket)}];",
    ]
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
