#!/usr/bin/env python3
"""Import the readable Retail69933 cooking-focus requirements into generated Rust.

TC a352b1fa DB2Metadata/DB2LoadInfo define FDID1002166/layout02074290,
RequiresSpellFocus at stored column6 (expanded column7). SpellFocusObject4
is Cooking Fire in local FDID1280620/layout782EE721. Encrypted records are
reported by db2_casc and never synthesized. Other focus types stay out of scope.
"""
import argparse
from pathlib import Path

import db2_casc

LAYOUT = 0x02074290
COOKING_FIRE = 4


def cooking_spell_ids(payload):
    header = db2_casc.read_header(payload)
    if header['layout_hash'] != LAYOUT or header['field_count'] != 7:
        raise ValueError('SpellCastingRequirements layout must be 02074290/7 fields')
    _, rows = db2_casc.decode(payload)
    if any(len(row) != 8 or row[0] != record_id for record_id, row in rows.items()):
        raise ValueError('SpellCastingRequirements identity/width differs')
    return sorted({row[1] for row in rows.values() if row[7] == COOKING_FIRE})


def write_cooking_spells(spells, output):
    groups = [spells[index:index + 12] for index in range(0, len(spells), 12)]
    body = '\n'.join('    ' + ', '.join(map(str, group)) + ',' for group in groups)
    output.write_text(
        '// Generated by scripts/import_toy_cooking_focus.py; do not edit.\n'
        '// Retail12.1.0.69933/TCa352b1fa;651 readable focus4 spells,3 encrypted records excluded.\n'
        'pub(super) const COOKING_SPELLS: &[u32] = &[\n' + body + '\n];\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--db2', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    spells = cooking_spell_ids(args.db2.read_bytes())
    if len(spells) != 651:
        raise ValueError('Pinned69933 import requires all651 readable cooking-focus spells')
    write_cooking_spells(spells, args.output)
    print(f'Imported {len(spells)} sourced cooking-focus spells into {args.output}')


if __name__ == '__main__':
    main()
