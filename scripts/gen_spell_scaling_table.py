#!/usr/bin/env python3
"""Generate crates/server-catalog/src/spell_scaling_data.rs.

Source (Retail 12.1.0.69933): local CASC game table gametables/spellscaling.txt
(FDID 1391660), saved as data/gametables/spellscaling.txt. Its class columns are all 0
in this build, so only the item columns TrinityCore `GetSpellScalingColumnForClass`
reads for negative scaling classes are kept.

Usage: scripts/gen_spell_scaling_table.py [GAMETABLES_DIR]
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAMETABLES = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "data/gametables")
OUT = ROOT / "crates/server-catalog/src/spell_scaling_data.rs"

CLASS_COLUMNS = [
    "Rogue", "Druid", "Hunter", "Mage", "Paladin", "Priest", "Shaman", "Warlock", "Warrior",
    "Death Knight", "Monk", "Demon Hunter", "Evoker", "Adventurer", "Traveler",
]
# `GetSpellScalingColumnForClass` (GameTables.h:289-307), scaling class -1 .. -10.
ITEM_COLUMNS = [
    ("-1 and -7", "Item"),
    ("-2", "Consumable"),
    ("-3", "Gem1"),
    ("-4", "Gem2"),
    ("-5", "Gem3"),
    ("-6", "Health"),
    ("-8", "DamageReplaceStat"),
    ("-9", "DamageSecondary"),
    ("-10", "Mana Consumable"),
]


def rows():
    lines = (GAMETABLES / "spellscaling.txt").read_text().splitlines()
    header = lines[0].split("\t")
    table = [dict(zip(header, line.split("\t"))) for line in lines[1:]]
    for index, row in enumerate(table, 1):
        assert int(row["Level"]) == index, index
        assert all(float(row[column]) == 0.0 for column in CLASS_COLUMNS), index
    return table


def main():
    table = rows()
    columns = ", ".join(f"{name} ({classes})" for classes, name in ITEM_COLUMNS)
    body = ",\n    ".join(
        "[" + ", ".join(repr(float(row[name])) for _, name in ITEM_COLUMNS) + "]" for row in table
    )
    out = [
        "// Generated by scripts/gen_spell_scaling_table.py; do not edit.",
        "// gtSpellScaling: local CASC 12.1.0.69933 gametables/spellscaling.txt (FDID 1391660).",
        "",
        f"/// `[level - 1]` = {columns}. The class columns are all 0.",
        "#[rustfmt::skip]",
        f"pub const SPELL_SCALING: [[f32; {len(ITEM_COLUMNS)}]; {len(table)}] = [",
        f"    {body},",
        "];",
        "",
    ]
    OUT.write_text("\n".join(out))


if __name__ == "__main__":
    main()
