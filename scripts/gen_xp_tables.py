#!/usr/bin/env python3
"""Generate crates/server-catalog/src/xp_data.rs.

Sources (Retail 12.1.0.69933):
- Local CASC game table gametables/xp.txt (FDID 1391661), saved as
  data/gametables/xp.txt: per-level Total (XP to next level), PerKill, Divisor.
- DB2 QuestXP from wago.tools (`db2.py` CSV root), saved as
  <csv-root>/12.1.0.69933/QuestXP.csv: Difficulty_0..9 per quest level.

Usage: scripts/gen_xp_tables.py [GAMETABLES_DIR] [DB2_CSV_DIR]
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAMETABLES = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "data/gametables")
DB2 = Path(sys.argv[2] if len(sys.argv) > 2 else ROOT / "../game-engine/data/db2/12.1.0.69933")
OUT = ROOT / "crates/server-catalog/src/xp_data.rs"


def xp_rows():
    lines = (GAMETABLES / "xp.txt").read_text().splitlines()
    header = lines[0].split("\t")
    rows = [dict(zip(header, line.split("\t"))) for line in lines[1:]]
    for index, row in enumerate(rows, 1):
        assert int(row["Level"]) == index, index
    return rows


def quest_xp_rows():
    with (DB2 / "QuestXP.csv").open(newline="") as f:
        rows = list(csv.DictReader(f))
    for index, row in enumerate(rows, 1):
        assert int(row["ID"]) == index, index
    return [[int(row[f"Difficulty_{d}"]) for d in range(10)] for row in rows]


def main():
    xp = xp_rows()
    quest = quest_xp_rows()
    out = [
        "// Generated by scripts/gen_xp_tables.py; do not edit.",
        "// gtXp: local CASC 12.1.0.69933 gametables/xp.txt (FDID 1391661).",
        "// QuestXP: wago.tools DB2 QuestXP, build 12.1.0.69933.",
        "",
        "/// XP from `level` to `level + 1`, `[level - 1]` (gtXp Total).",
        "#[rustfmt::skip]",
        f"pub const XP_TO_NEXT_LEVEL: [u32; {len(xp)}] = [{', '.join(r['Total'] for r in xp)}];",
        "",
        "/// Base kill XP, `[level - 1]` (gtXp PerKill).",
        "#[rustfmt::skip]",
        f"pub const XP_PER_KILL: [f32; {len(xp)}] = [{', '.join(repr(float(r['PerKill'])) for r in xp)}];",
        "",
        "/// Kill XP divisor, `[level - 1]` (gtXp Divisor).",
        "#[rustfmt::skip]",
        f"pub const XP_DIVISOR: [f32; {len(xp)}] = [{', '.join(repr(float(r['Divisor'])) for r in xp)}];",
        "",
        "/// Quest XP `[quest level - 1][RewardXPDifficulty]` (QuestXP.Difficulty).",
        "#[rustfmt::skip]",
        f"pub const QUEST_XP: [[u32; 10]; {len(quest)}] = [",
    ]
    out += ["    [" + ", ".join(map(str, row)) + "]," for row in quest]
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
