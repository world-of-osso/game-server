#!/usr/bin/env python3
"""Compile traditional reputation rank actors from pinned Faction metadata."""
import argparse
import csv
import hashlib
from pathlib import Path


def generate_source(source, output):
    with source.open() as stream:
        rows = list(csv.DictReader(stream))
    paragon_targets = {int(row['ParagonFactionID']) for row in rows} - {0}
    factions = sorted(int(row['ID']) for row in rows
                      if int(row['ReputationIndex']) >= 0
                      and int(row['FriendshipRepID']) == 0
                      and int(row['RenownCurrencyID']) == 0
                      and int(row['ID']) not in paragon_targets)
    lines = [
        '// Generated by scripts/import_achievement_rank_factions.py; do not edit.',
        f'// Mainline12.1.0.69933 Faction SHA256 {hashlib.sha256(source.read_bytes()).hexdigest()}.',
        '// TC ReputationMgr420-421/543-558: friendship has no rank counters;',
        '// renown/paragon progress is not a traditional standing change.',
        'pub(super) const TRADITIONAL_RANK_FACTIONS: &[u32] = &[',
    ]
    lines.extend('    ' + ', '.join(map(str, factions[start:start + 12])) + ','
                 for start in range(0, len(factions), 12))
    lines += ['];', '']
    output.write_text('\n'.join(lines))
    print(f'Compiled {len(factions)} traditional rank factions.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--factions', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate_source(args.factions, args.output)


if __name__ == '__main__':
    main()
