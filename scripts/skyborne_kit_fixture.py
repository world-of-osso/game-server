#!/usr/bin/env python3
"""Generate the owned importer→regeneration SQLite fixture used by native kit tests."""

import argparse
from contextlib import closing
import importlib.util
import json
from pathlib import Path
import sqlite3

import content_policy
from content_common import Report
import skyborne_data

SCRIPTS = Path(__file__).resolve().parent
REFERENCE = SCRIPTS / "reference/forever-1.60.1.70205"


def fixture_database(source_dir):
    db = sqlite3.connect(":memory:")
    db.executescript((SCRIPTS / "db2_schema.sql").read_text())
    db.executescript((SCRIPTS / "tdb_schema.sql").read_text())
    # Empty currency schema from the existing native fixture; merchant loading queries it.
    db.execute("""CREATE TABLE currency_types (
        ID INTEGER PRIMARY KEY, Name_lang TEXT NOT NULL, Description_lang TEXT NOT NULL,
        InventoryIconFileID INTEGER NOT NULL, MaxQty INTEGER NOT NULL,
        MaxEarnablePerWeek INTEGER NOT NULL, AwardConditionID INTEGER NOT NULL,
        MaxQtyWorldStateID INTEGER NOT NULL, Flags_0 INTEGER NOT NULL, Flags_1 INTEGER NOT NULL)""")
    spec = importlib.util.spec_from_file_location("player_starts", SCRIPTS / "import-player-starts.py")
    starts = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(starts)
    starts.import_starts(db, starts.DEFAULT_DUMP)
    db.execute(
        "CREATE TABLE content_npc_vendor (entry INTEGER,slot INTEGER,item INTEGER,maxcount INTEGER,incrtime INTEGER,ExtendedCost INTEGER)"
    )
    retail = json.loads((REFERENCE / "retail-kit-runtime-rows.json").read_text())
    for table, records in retail.items():
        for row in records:
            db.execute(
                f"INSERT INTO {table} ({','.join(row)}) VALUES ({','.join('?' for _ in row)})",
                tuple(row.values()),
            )
    expected_retail = {
        table: db.execute(f"SELECT * FROM {table} ORDER BY ID").fetchall()
        for table in retail
    }
    skyborne_data.import_rows(db, skyborne_data.load_rows(source_dir))
    content_policy.create_map_table(db, "item_map", {})
    retail_ids = {row["ID"] for row in retail["item"]}
    for _ in range(2):
        content_policy.build_items(db, {}, {}, retail_ids, Report())
        db.execute("DROP TABLE temp.item_source")
    for table in retail:
        # Authored loadouts are additive; original row identities/masks stay unchanged.
        ids = [row["ID"] for row in retail[table]]
        actual = db.execute(
            f"SELECT * FROM {table} WHERE ID IN ({','.join('?' for _ in ids)}) ORDER BY ID",
            ids,
        ).fetchall()
        if actual != expected_retail[table]:
            raise ValueError(f"fixture regeneration changed Retail {table}")
    # Runtime Need metadata uses this projection of canonical world.db ChrClasses.
    # Only classes present in the fixture loadouts are needed.
    db.execute("DROP TABLE chr_classes")
    db.execute("CREATE TABLE chr_classes (ID INTEGER PRIMARY KEY, ArmorTypeMask INTEGER NOT NULL)")
    db.executemany(
        "INSERT INTO chr_classes VALUES (?, ?)",
        [(1, 113), (3, 41), (4, 37), (7, 2665), (8, 35), (11, 2341)],
    )
    retained = (
        set(retail)
        | {
            "content_item",
            "content_npc_vendor",
            "tdb_npc_vendor",
            "currency_types",
            "chr_classes",
            "spell_equipped_items",
            "db2_row_source",
            "spell",
            "spell_name",
            "spell_effect",
            "mount",
            "tdb_playercreateinfo",
            "tdb_playercreateinfo_item",
            "tdb_playercreateinfo_action",
            "skyborne_content_item",
        }
        | {f"skyborne_{table}" for table in skyborne_data.ISOLATED_TABLES}
    )
    for (table,) in db.execute(
        "SELECT name FROM sqlite_master WHERE type='table'"
    ).fetchall():
        if table not in retained:
            db.execute(f'DROP TABLE "{table}"')
    return db


def fixture_sql(source_dir):
    with closing(fixture_database(source_dir)) as db:
        return (
            "-- Generated by scripts/skyborne_kit_fixture.py; no live DB/extraction.\n"
            + "\n".join(db.iterdump())
            + "\n"
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--source-dir", type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(
        "// Generated by scripts/skyborne_kit_fixture.py; no live DB/extraction.\n"
        + 'pub(super) const SQL: &str = r#"'
        + fixture_sql(args.source_dir)
        + '"#;\n'
    )


if __name__ == "__main__":
    main()
