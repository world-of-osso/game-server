#!/usr/bin/env python3
"""Compile pinned criteria whose only condition is one TC PlayerHasAura8 leaf."""
import argparse
import collections
import hashlib
from pathlib import Path

from import_achievement_single_modifiers import read_rows

PLAYER_HAS_AURA = 8
CONDITIONS = ('StartEvent', 'StartTimer', 'FailEvent', 'EligibilityWorldStateID')
# Structural (CompleteAchievement8) or account-recomputed (81/156/185/186) types are
# never evaluated at a player's criteria update, so an aura cannot gate them.
UNGATED_TYPES = {8, 81, 156, 185, 186}


def qualified_aura_rules(criteria, modifiers):
    """Criteria ID -> (modifier root, spell) for only All4 -> SingleTrue2 PlayerHasAura."""
    children = collections.defaultdict(list)
    for row_id, row in modifiers.items():
        children[int(row['Parent'])].append(row_id)
    qualified = {}
    for row_id, row in criteria.items():
        if int(row['Type']) in UNGATED_TYPES or any(int(row[key]) for key in CONDITIONS):
            continue
        root = int(row['ModifierTreeId'])
        branch = children[root]
        if root not in modifiers or len(branch) != 1:
            continue
        parent, leaf = modifiers[root], modifiers[branch[0]]
        if (int(parent['Operator']), int(parent['Type']), int(parent['Asset'])) != (4, 0, 0):
            continue
        if (int(leaf['Operator']), int(leaf['Type'])) != (2, PLAYER_HAS_AURA) or children[branch[0]]:
            continue
        if any(int(node[key]) for node in (parent, leaf) for key in ('SecondaryAsset', 'TertiaryAsset')):
            continue
        if int(leaf['Asset']) > 0:
            qualified[row_id] = (root, int(leaf['Asset']))
    return qualified


def generate_source(criteria_path, modifiers_path, output):
    qualified = qualified_aura_rules(read_rows(criteria_path), read_rows(modifiers_path))
    lines = [
        '// Generated by scripts/import_achievement_aura_rules.py; do not edit.',
        '// TC CriteriaHandler.cpp1798-1801 PlayerHasAura8; only All4 -> SingleTrue2.',
        f'// Criteria SHA256 {hashlib.sha256(criteria_path.read_bytes()).hexdigest()}.',
        f'// ModifierTree SHA256 {hashlib.sha256(modifiers_path.read_bytes()).hexdigest()}.',
        'pub(super) fn aura_rule(criteria: u32, modifier: u32) -> Option<u32> {',
        '    match (criteria, modifier) {',
    ]
    for criterion, (modifier, spell) in sorted(qualified.items()):
        lines.append(f'        ({criterion}, {modifier}) => Some({spell}),')
    lines += ['        _ => None,', '    }', '}', '']
    output.write_text('\n'.join(lines))
    print(f'Compiled {len(qualified)} PlayerHasAura predicates.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--criteria', type=Path, required=True)
    parser.add_argument('--modifiers', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate_source(args.criteria, args.modifiers, args.output)


if __name__ == '__main__':
    main()
