#!/usr/bin/env python3
"""Compile sourced node-ownership and literal-comparison WorldStateExpression subsets."""
import argparse
import csv
import hashlib
import operator
import struct
from pathlib import Path

# TC a352b1fa DBCEnums3214–3250 / ConditionMgr3639–3758.
CLAUSE = struct.Struct('<BiBBBiBB')
WORLD_STATE, CONSTANT = 2, 1
NO_ARITHMETIC, EQUAL, OR, END = 0, 1, 2, 0
OWNED_NODE_STATES = {1778, 1779}  # BattleForGilneas57–58; Arathi shares these fields.
MAX_OWNED_NODES = 5  # Native Arathi5 / Gilneas3; no other node-map producer.


def decode_clause(data, offset):
    """One WorldState == Constant comparison followed by a boolean operator."""
    left_type, state, left_op, comparison, right_type, count, right_op, logic = CLAUSE.unpack_from(data, offset)
    if (left_type, left_op, comparison, right_type, right_op) != (
            WORLD_STATE, NO_ARITHMETIC, EQUAL, CONSTANT, NO_ARITHMETIC):
        return None
    return state, count, logic


def decode_node_count_expression(expression):
    """Either team's occupied-node count equals the same authored positive count."""
    data = bytes.fromhex(expression)
    if len(data) != 1 + 2 * CLAUSE.size or not data[0]:
        return None
    first = decode_clause(data, 1)
    second = decode_clause(data, 1 + CLAUSE.size)
    if first is None or second is None:
        return None
    first_state, first_count, first_logic = first
    second_state, second_count, second_logic = second
    if {first_state, second_state} != OWNED_NODE_STATES:
        return None
    if (first_logic, second_logic) != (OR, END) or first_count != second_count:
        return None
    return first_count if 1 <= first_count <= MAX_OWNED_NODES else None


COMPARISONS = {1: operator.eq, 2: operator.ne, 3: operator.lt,
               4: operator.le, 5: operator.gt, 6: operator.ge}


def decode_constant_expression(expression):
    """TC EvalRelOp: enabled, two signed literals, one comparison, no arithmetic/logic."""
    data = bytes.fromhex(expression)
    if len(data) != 1 + CLAUSE.size or not data[0]:
        return None
    left_type, left, left_op, comparison, right_type, right, right_op, logic = CLAUSE.unpack_from(data, 1)
    if (left_type, left_op, right_type, right_op, logic) != (
            CONSTANT, NO_ARITHMETIC, CONSTANT, NO_ARITHMETIC, END):
        return None
    compare = COMPARISONS.get(comparison)
    return compare(left, right) if compare is not None else None


def qualified_constant_expressions(expressions):
    qualified = {}
    for expression_id, row in expressions.items():
        try:
            value = decode_constant_expression(row['Expression'])
        except ValueError as error:
            raise ValueError(f'WorldStateExpression{expression_id}: malformed hexadecimal bytecode') from error
        if value is not None:
            qualified[expression_id] = value
    return qualified


def qualified_node_counts(expressions):
    qualified = {}
    for expression_id, row in expressions.items():
        try:
            count = decode_node_count_expression(row['Expression'])
        except ValueError as error:
            raise ValueError(f'WorldStateExpression{expression_id}: malformed hexadecimal bytecode') from error
        if count is not None:
            qualified[expression_id] = count
    return qualified


def write_source(expressions_path, output):
    with expressions_path.open() as source:
        rows = {int(row['ID']): row for row in csv.DictReader(source)}
    qualified = qualified_node_counts(rows)
    constants = qualified_constant_expressions(rows)
    lines = [
        '// Generated by scripts/import_achievement_node_counts.py; do not edit.',
        '// TC a352b1fa ConditionMgr3639–3758: exact occupied-node equality OR for1778/1779,',
        '// plus enabled signed-literal comparisons with no arithmetic/functions/state reads/logic.',
        f'// WorldStateExpression SHA256 {hashlib.sha256(expressions_path.read_bytes()).hexdigest()}.',
        'pub(super) fn required_owned_nodes(expression: u32) -> Option<u8> {',
        '    match expression {',
    ]
    lines.extend(f'        {expression} => Some({count}),' for expression, count in sorted(qualified.items()))
    lines += ['        _ => None,', '    }', '}', '',
              'pub(super) fn constant_expression(expression: u32) -> Option<bool> {',
              '    match expression {']
    lines.extend(f'        {expression} => Some({str(value).lower()}),'
                 for expression, value in sorted(constants.items()))
    lines += ['        _ => None,', '    }', '}', '']
    output.write_text('\n'.join(lines))
    print(f'Compiled {len(qualified)} node-count and {len(constants)} literal expressions.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--expressions', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    write_source(args.expressions, args.output)


if __name__ == '__main__':
    main()
