#!/usr/bin/env python3
"""Compile pinned criteria whose only condition is All4 of SingleTrue player-fact leaves."""
import argparse
import collections
import hashlib
from pathlib import Path

from import_achievement_single_modifiers import read_rows

# TC CriteriaHandler.cpp ModifierTreeType leaves read from the reference player alone:
# PlayerHasAura8 (1798), PlayerIsInArea17 (1842), PlayerRace25 (1886), PlayerClass26
# (1890), PlayerMap32 (1922), PlayerLevelEqualOrGreaterThan69 (2094),
# PlayerLevelEqualOrLessThan71 (2102).
PLAYER_FACTS = {8, 17, 25, 26, 32, 69, 71}
CONDITIONS = ('StartEvent', 'StartTimer', 'FailEvent', 'EligibilityWorldStateID')
# Structural (CompleteAchievement8) or account-recomputed (81/156/185/186) types are
# never evaluated at a player's criteria update, so a player fact cannot gate them.
UNGATED_TYPES = {8, 81, 156, 185, 186}


def plain(node):
    return not int(node['SecondaryAsset']) and not int(node['TertiaryAsset'])


def qualified_player_facts(criteria, modifiers):
    """Criteria ID -> (modifier root, ((ModifierTreeType, Asset), ...))."""
    children = collections.defaultdict(list)
    for row_id, row in modifiers.items():
        children[int(row['Parent'])].append(row_id)
    qualified = {}
    for row_id, row in criteria.items():
        if int(row['Type']) in UNGATED_TYPES or any(int(row[key]) for key in CONDITIONS):
            continue
        root = int(row['ModifierTreeId'])
        if root not in modifiers or not children[root]:
            continue
        parent = modifiers[root]
        if (int(parent['Operator']), int(parent['Type']), int(parent['Asset'])) != (4, 0, 0) or not plain(parent):
            continue
        leaves = [modifiers[child] for child in children[root]]
        if any(children[child] for child in children[root]):
            continue
        if all(int(leaf['Operator']) == 2 and int(leaf['Type']) in PLAYER_FACTS
               and int(leaf['Asset']) > 0 and plain(leaf) for leaf in leaves):
            facts = tuple(sorted((int(leaf['Type']), int(leaf['Asset'])) for leaf in leaves))
            qualified[row_id] = (root, facts)
    return qualified


def generate_source(criteria_path, modifiers_path, output):
    qualified = qualified_player_facts(read_rows(criteria_path), read_rows(modifiers_path))
    lines = [
        '// Generated by scripts/import_achievement_player_facts.py; do not edit.',
        '// TC player-only ModifierTree leaves (8/17/25/26/32/69/71); only All4 -> SingleTrue2.',
        f'// Criteria SHA256 {hashlib.sha256(criteria_path.read_bytes()).hexdigest()}.',
        f'// ModifierTree SHA256 {hashlib.sha256(modifiers_path.read_bytes()).hexdigest()}.',
        'pub(super) fn player_facts(criteria: u32, modifier: u32) -> Option<&\'static [(u32, u32)]> {',
        '    match (criteria, modifier) {',
    ]
    for criterion, (modifier, facts) in sorted(qualified.items()):
        listed = ', '.join(f'({kind}, {asset})' for kind, asset in facts)
        lines.append(f'        ({criterion}, {modifier}) => Some(&[{listed}]),')
    lines += ['        _ => None,', '    }', '}', '']
    output.write_text('\n'.join(lines))
    print(f'Compiled {len(qualified)} player-fact predicates.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--criteria', type=Path, required=True)
    parser.add_argument('--modifiers', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate_source(args.criteria, args.modifiers, args.output)


if __name__ == '__main__':
    main()
