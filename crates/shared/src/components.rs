/// A single resource pool (current/max) for a specific resource type.
///
/// Each class has a primary resource (Rage for Warriors, Energy for Rogues,
/// Mana for casters) plus potential secondary resources (Combo Points, Holy Power).
/// Resource behavior varies by type:
/// - **Mana**: starts full, drains on cast, regenerates passively
/// - **Rage**: starts empty, generated by damage dealt/taken, decays out of combat
/// - **Energy**: starts full, regenerates at 10/sec, capped at 100
/// - **Focus**: like energy but for Hunters (regenerates at 5/sec)
/// - **Combo Points**: 0–5, built by abilities, consumed by finishers
/// - **Holy Power**: 0–5, built by abilities, consumed by spenders
/// - **Runic Power**: like rage, generated by rune abilities, decays out of combat
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct ResourcePool {
    pub resource_type: ResourceType,
    pub current: f32,
    pub max: f32,
    /// Passive regeneration per second (0.0 for rage/combo points).
    pub regen_per_sec: f32,
    /// Whether the resource decays out of combat (rage, runic power).
    pub decays_out_of_combat: bool,
}

impl ResourcePool {
    /// Create a default pool for a resource type with standard WoW defaults.
    ///
    /// | Type | Max | Start | Regen | Decays |
    /// |------|-----|-------|-------|--------|
    /// | Mana | 0 (stat-based) | 0 | 0 (formula) | no |
    /// | Rage/Runic | 100 | 0 | 0 | yes (2/sec) |
    /// | Energy | 100 | 100 | 10/sec | no |
    /// | Focus | 100 | 100 | 5/sec | no |
    /// | Combo/Holy | 5 | 0 | 0 | no |
    pub fn for_type(resource_type: ResourceType) -> Self {
        let (current, max, regen, decays) = match resource_type {
            ResourceType::Mana => (0.0, 0.0, 0.0, false),
            ResourceType::Rage | ResourceType::RunicPower => (0.0, 100.0, 0.0, true),
            ResourceType::Energy => (100.0, 100.0, 10.0, false),
            ResourceType::Focus => (100.0, 100.0, 5.0, false),
            ResourceType::ComboPoints | ResourceType::HolyPower => (0.0, 5.0, 0.0, false),
        };
        Self {
            resource_type,
            current,
            max,
            regen_per_sec: regen,
            decays_out_of_combat: decays,
        }
    }

    /// Spend a resource. Returns `true` if the entity had enough.
    pub fn spend(&mut self, amount: f32) -> bool {
        if self.current < amount {
            return false;
        }
        self.current -= amount;
        true
    }

    /// Generate (add) a resource, clamped to max.
    pub fn generate(&mut self, amount: f32) {
        self.current = (self.current + amount).min(self.max);
    }

    /// Tick passive regeneration by `dt` seconds.
    pub fn tick_regen(&mut self, dt: f32) {
        if self.regen_per_sec > 0.0 {
            self.generate(self.regen_per_sec * dt);
        }
    }

    /// Tick decay (out of combat). Rage/Runic Power lose 2/sec.
    pub fn tick_decay(&mut self, dt: f32) {
        if self.decays_out_of_combat {
            self.current = (self.current - RESOURCE_DECAY_RATE * dt).max(0.0);
        }
    }
}

/// Rate at which rage/runic power decay out of combat (per second).
const RESOURCE_DECAY_RATE: f32 = 2.0;

/// Collection of resource pools on an entity.
///
/// Most entities have 1–2 resources (e.g. Mana + Combo Points for a Rogue
/// who multiclasses, or just Rage for a Warrior).
#[derive(Component, Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
pub struct Resources {
    pub pools: Vec<ResourcePool>,
}

impl Resources {
    /// Get a resource pool by type.
    pub fn get(&self, resource_type: ResourceType) -> Option<&ResourcePool> {
        self.pools.iter().find(|p| p.resource_type == resource_type)
    }

    /// Get a mutable resource pool by type.
    pub fn get_mut(&mut self, resource_type: ResourceType) -> Option<&mut ResourcePool> {
        self.pools.iter_mut().find(|p| p.resource_type == resource_type)
    }

    /// Whether the entity has enough of a resource to spend.
    pub fn can_afford(&self, resource_type: ResourceType, amount: f32) -> bool {
        self.get(resource_type).is_some_and(|p| p.current >= amount)
    }

    /// Create a standard resource pool for a class's primary resource.
    pub fn with_primary(resource_type: ResourceType) -> Self {
        Self {
            pools: vec![ResourcePool::for_type(resource_type)],
        }
    }
}

